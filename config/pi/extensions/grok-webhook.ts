// Tell another device that the Pi coding agent is waiting for the user.
// Fires on `agent_settled`, the same notification-only boundary as
// notification-sound.ts: Pi has finished automatic work for a run and will not
// continue on its own. The handler must not change the run, so the POST is not
// awaited and its rejection is discarded.
//
// Deployed to ~/.pi/agent/extensions/ by modules/shared/agents-pi.nix. Pi loads
// *.ts extensions from there with jiti, so there is no build step. Delivery is
// best-effort: a failure never affects the session and is never printed.
// Kept in its own file: herdr-agent-state.ts is generated by herdr and
// overwritten on herdr updates.
//
// Configuration is environment only, and neither value belongs in this repo.
// Both must be set or this extension is a silent no-op:
//   GROK_WEBHOOK_URL            HTTPS URL on port 443 (the default). Any other
//                               scheme, an explicit non-443 port, or userinfo
//                               is a silent no-op.
//   GROK_WEBHOOK_AUTHORIZATION  sent verbatim as the Authorization header.
//                               Include the scheme yourself ("Bearer ...").
// Wire them from a secret store later (sops-nix or equivalent). This flake
// does not provision them.
//
// The default sandbox profile (config/agents/cloud-restricted.sb) already
// allows outbound TCP 443 to any host. Seatbelt cannot name a host, and the
// model APIs need that same egress, so no profile change is required for an
// arbitrary webhook. The pi-sandboxed wrapper preserves the caller environment
// (it only scrubs GitHub token variables), so these two variables reach this
// process. The free-tier wrapper rebuilds the environment with `env -i` and an
// allowlist that omits them on purpose: that profile is for low-trust providers
// and must not gain this secret, so the extension stays a no-op there even
// though that profile also allows TCP 443.
//
// The secret is visible to the model, like every other inherited variable
// (config/agents/README.md, "Environment variables are visible to the model").
// Accepted for the same reason as SLACK_USER_TOKEN: the sandbox is defense in
// depth, not a boundary against this user's own tooling. Do not export the
// value if that exposure is unacceptable.

import { readFileSync, statSync } from "node:fs";
import { hostname } from "node:os";
import { basename, dirname, join, resolve } from "node:path";

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const TIMEOUT_MS = 3000;
const MAX_GIT_WALK = 32;
const MAX_HEAD_BYTES = 4096;

// One POST per agent run. `agent_start` bumps the generation (retries and
// compaction start another low-level run before `agent_settled`); the settle
// handler sends only when this generation has not been sent yet.
let runGeneration = 0;
let notifiedGeneration = -1;

function envValue(name: string): string | undefined {
  const value = process.env[name]?.trim();
  return value ? value : undefined;
}

function webhookConfig(): { url: string; authorization: string } | undefined {
  const url = envValue("GROK_WEBHOOK_URL");
  const authorization = envValue("GROK_WEBHOOK_AUTHORIZATION");
  if (!url || !authorization) return undefined;
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:") return undefined;
    if (parsed.port !== "" && parsed.port !== "443") return undefined;
    if (parsed.username !== "" || parsed.password !== "") return undefined;
  } catch {
    return undefined;
  }
  return { url, authorization };
}

function readBounded(path: string): string | undefined {
  try {
    const info = statSync(path);
    if (!info.isFile() || info.size > MAX_HEAD_BYTES) return undefined;
    return readFileSync(path, "utf8");
  } catch {
    return undefined;
  }
}

// `undefined` means this directory is not a git dir. `null` means it is, but
// HEAD is detached or otherwise not a branch ref.
function readBranch(dir: string): string | null | undefined {
  const gitPath = join(dir, ".git");
  const pointer = readBounded(gitPath);
  if (pointer !== undefined) {
    if (!pointer.startsWith("gitdir:")) return null;
    const gitdir = pointer.slice("gitdir:".length).trim();
    if (!gitdir || gitdir.includes("\0")) return null;
    const head = readBounded(join(resolve(dir, gitdir), "HEAD"));
    return head === undefined ? null : branchFromHead(head);
  }
  const head = readBounded(join(gitPath, "HEAD"));
  if (head === undefined) return undefined;
  return branchFromHead(head);
}

function branchFromHead(head: string): string | null {
  const line = head.split("\n", 1)[0]?.trim() ?? "";
  const match = /^ref: refs\/heads\/(.+)$/.exec(line);
  if (!match) return null;
  const branch = match[1].trim();
  return branch || null;
}

// Repo directory name when a `.git` is found within a short walk, otherwise
// the working directory's own name. Never a full path. Reads HEAD directly
// instead of spawning `git` (the sandbox git shim, and no conversation data).
function projectFacts(cwd: string): { project: string; branch: string | null } {
  let dir = cwd;
  for (let i = 0; i < MAX_GIT_WALK; i++) {
    const branch = readBranch(dir);
    if (branch !== undefined) {
      const name = basename(dir);
      return { project: name || dir, branch };
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  const name = basename(cwd);
  return { project: name || cwd, branch: null };
}

function post(url: string, authorization: string, payload: unknown): void {
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
    timer.unref?.();
    // Not awaited. `redirect: "error"` so a redirect cannot carry the
    // Authorization header to another host. Keep the abort deadline armed
    // until the body is cancelled; clearing it when headers arrive would leave
    // cleanup uncovered. unref only detaches the timer from the event loop; it
    // does not bound the socket.
    void (async () => {
      try {
        const response = await fetch(url, {
          method: "POST",
          headers: {
            "content-type": "application/json",
            authorization,
          },
          body: JSON.stringify(payload),
          redirect: "error",
          signal: controller.signal,
        });
        // Delivery is best-effort; discard the response body so the request
        // cannot stay open on an unconsumed stream.
        await response.body?.cancel();
      } catch {
        // Delivery is best-effort and must not affect the session.
      } finally {
        clearTimeout(timer);
      }
    })();
  } catch {
    // Best-effort: ignore a failure while arming the abort timer.
  }
}

export default function (pi: ExtensionAPI) {
  // Environment-only configuration, captured once at extension initialization.
  // Without both values there is nothing to send, so skip hook registration
  // entirely instead of checking on every settle. Changing or removing the
  // values mid-session takes effect only after a reload.
  const target = webhookConfig();
  if (!target) return;

  pi.on("agent_start", () => {
    runGeneration += 1;
  });

  pi.on("agent_settled", (event, ctx) => {
    try {
      // Only an interactive session. Stay silent in print/JSON/RPC runs.
      if (ctx && ctx.mode && ctx.mode !== "tui") return;
      if (notifiedGeneration === runGeneration) return;

      const cwd = (ctx && ctx.cwd) || process.cwd();
      const { project, branch } = projectFacts(cwd);
      const pane = envValue("HERDR_PANE_ID") ?? null;
      const payload = {
        agent: "pi",
        state: event && event.aborted ? "aborted" : "done",
        project,
        branch,
        herdr: process.env.HERDR_ENV === "1",
        pane,
        hostname: hostname(),
        timestamp: new Date().toISOString(),
      };
      notifiedGeneration = runGeneration;
      post(target.url, target.authorization, payload);
    } catch {
      // Status delivery is best-effort and must not affect the session.
    }
  });
}
